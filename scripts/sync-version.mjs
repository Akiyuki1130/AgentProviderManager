#!/usr/bin/env node
// 版本号同步工具：仓库根目录的 VERSION 文件是唯一真源，本脚本把它分发到所有消费点。
//
//   node scripts/sync-version.mjs          就地更新所有派生文件
//   node scripts/sync-version.mjs --check  只校验；发现不一致时以非零码退出
//
// 修改版本只需编辑 VERSION，然后运行一次本脚本。若忘记运行，根目录的
// version_sync_test.go（go test ./...）会因不一致而失败，不会静默漂移。
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const checkOnly = process.argv.includes('--check')
const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/

const read = (rel) => readFileSync(join(root, rel), 'utf8')
const eolOf = (raw) => (raw.includes('\r\n') ? '\r\n' : '\n')
const md5 = (s) => createHash('md5').update(Buffer.from(s, 'utf8')).digest('hex')

const version = read('VERSION').trim()
if (!SEMVER.test(version)) {
  console.error(`VERSION 不是合法的语义化版本号：${JSON.stringify(version)}`)
  process.exit(2)
}

// 待写文件；stage 只在内容确实变化时才登记，保证重复运行是无副作用的。
const changes = []
function stage(path, current, next) {
  if (current !== next) changes.push({ path, content: next })
}

// 1) internal/core/version_gen.go —— Go 侧版本常量（AppVersion）
{
  const path = 'internal/core/version_gen.go'
  const lines = [
    '// Code generated by scripts/sync-version.mjs from the repository VERSION file. DO NOT EDIT.',
    '',
    'package core',
    '',
    '// AppVersion 是应用版本号，唯一真源为仓库根目录的 VERSION 文件。',
    '// 修改 VERSION 后运行 `node scripts/sync-version.mjs` 重新生成。',
    `const AppVersion = ${JSON.stringify(version)}`,
    '',
  ]
  const current = existsSync(join(root, path)) ? read(path) : ''
  stage(path, current, lines.join('\n').split('\n').join(current ? eolOf(current) : '\r\n'))
}

// 2) wails.json —— Windows PE 版本信息与构建元数据
{
  const raw = read('wails.json')
  stage('wails.json', raw, raw.replace(/("productVersion"\s*:\s*")[^"]*(")/, `$1${version}$2`))
}

// 3) frontend/package.json + 4) package.json.md5
// md5 必须与 package.json 的字节一致：Wails 用它判断是否需要重新 npm install。
{
  const raw = read('frontend/package.json')
  const next = raw.replace(/("version"\s*:\s*")[^"]*(")/, `$1${version}$2`)
  stage('frontend/package.json', raw, next)
  const md5Path = 'frontend/package.json.md5'
  stage(md5Path, existsSync(join(root, md5Path)) ? read(md5Path) : '', md5(next))
}

// 5) frontend/package-lock.json —— 只有根包的两处 version，依赖项不动
{
  const raw = read('frontend/package-lock.json')
  let seen = 0
  const next = raw.replace(/("version"\s*:\s*")[^"]*(")/g, (m, a, b) => {
    seen += 1
    return seen <= 2 ? `${a}${version}${b}` : m
  })
  stage('frontend/package-lock.json', raw, next)
}

// 6) README.md —— 标题与下载文件名中的版本
{
  const raw = read('README.md')
  const next = raw
    .replace(/^# Agent Provider Manager[^\r\n]*/m, `# Agent Provider Manager ${version}`)
    .replace(/AgentProviderManager-[0-9A-Za-z.\-]+-windows-amd64/g, `AgentProviderManager-${version}-windows-amd64`)
  stage('README.md', raw, next)
}

if (checkOnly) {
  if (changes.length === 0) {
    console.log(`版本号一致：${version}`)
    process.exit(0)
  }
  console.error(`版本号不一致（VERSION=${version}），请运行 node scripts/sync-version.mjs：`)
  for (const c of changes) console.error(`  - ${c.path}`)
  process.exit(1)
}

for (const c of changes) {
  writeFileSync(join(root, c.path), c.content)
  console.log(`updated ${c.path}`)
}
console.log(changes.length === 0 ? `版本号已一致：${version}` : `已同步到 ${version}（${changes.length} 个文件）`)
